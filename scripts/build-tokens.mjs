// Reads design-tokens/tokens.json (W3C DTCG format, as exported by Penpot)
// and writes src/styles/tokens.generated.css for Tailwind v4's @theme.
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = resolve(root, 'design-tokens/tokens.json')
const out = resolve(root, 'src/styles/tokens.generated.css')

const tree = JSON.parse(readFileSync(src, 'utf8'))

// Flatten the token tree into [path[], token] pairs, carrying $type down.
function walk(node, path = [], inheritedType) {
  const rows = []
  const type = node.$type ?? inheritedType
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    if (value && typeof value === 'object' && '$value' in value) {
      rows.push([[...path, key], { ...value, $type: value.$type ?? type }])
    } else if (value && typeof value === 'object') {
      rows.push(...walk(value, [...path, key], type))
    }
  }
  return rows
}

// Penpot and Tokens Studio use slightly different $type names, so accept both.
const TYPE_GROUP = {
  color: 'color',
  borderradius: 'radius',
  dimension: 'radius',
  shadow: 'shadow',
  boxshadow: 'shadow',
  fontfamily: 'font',
  fontfamilies: 'font',
}

const px = (v) => (/^-?\d+(\.\d+)?$/.test(String(v)) ? `${v}px` : String(v))
const shadowCss = (s) => `${px(s.offsetX)} ${px(s.offsetY)} ${px(s.blur)} ${px(s.spread)} ${s.color}`

const lines = []
const fontLines = []
for (const [path, token] of walk(tree)) {
  const group = TYPE_GROUP[String(token.$type).toLowerCase()]
  if (!group) {
    console.warn(`skip ${path.join('.')}: unknown $type "${token.$type}"`)
    continue
  }
  const name = path.slice(1).join('-')
  const v = token.$value
  if (group === 'color') lines.push(`  --color-${name}: ${v};`)
  if (group === 'radius') lines.push(`  --radius-${name}: ${px(v)};`)
  if (group === 'shadow') {
    const list = Array.isArray(v) ? v : [v]
    lines.push(`  --shadow-${name}: ${list.map(shadowCss).join(', ')};`)
  }
  if (group === 'font') {
    // Prefer the next/font variable when present, fall back to the family name
    // (Storybook has no next/font).
    const generic = name === 'mono' ? 'monospace' : 'sans-serif'
    fontLines.push(`  --font-${name}: var(--font-${{ display: 'bebas', sans: 'dm-sans', mono: 'dm-mono' }[name] ?? name}, "${v}"), ${generic};`)
  }
}

const css = `/* GENERATED by scripts/build-tokens.mjs from design-tokens/tokens.json.
   Do not edit by hand. Change the tokens in Penpot, export, then run \`npm run tokens\`. */
@theme {
${lines.join('\n')}
}

/* inline: next/font sets its variables below :root, so the value must be
   substituted into each utility instead of resolved at :root. */
@theme inline {
${fontLines.join('\n')}
}
`
writeFileSync(out, css)
console.log(`wrote ${out} (${lines.length + fontLines.length} tokens)`)
